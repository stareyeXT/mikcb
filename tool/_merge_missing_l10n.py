LOCALE_FILE = {"ja": "app_ja.arb", "ko": "app_ko.arb"}
BATCH = {"ja": JA, "ko": KO}


def append_keys(path: Path, keys: dict) -> list:
    text = path.read_text(encoding="utf-8")
    added = []
    insert_lines = []
    for key, value in keys.items():
        if re.search(rf'^s*"{re.escape(key)}"s*:', text, re.M):
            continue
        added.append(key)
        insert_lines.append(f'  "{key}": {json.dumps(value, ensure_ascii=False)},')
    if not insert_lines:
        return added
    text = text.rstrip()
    if text.endswith("}"):
        text = text[:-1].rstrip() + "\n" + "\n".join(insert_lines) + "\n}\n"
    path.write_text(text, encoding="utf-8")
    return added


def main():
    # 校验：BATCH 键集合必须与 untranslated 清单完全一致
    missing = json.loads((ROOT / "l10n_untranslated.json").read_text(encoding="utf-8"))
    zh = json.loads((ARB_DIR / "app_zh.arb").read_text(encoding="utf-8"))
    for lang in ("ja", "ko"):
        expected = set(missing[lang])
        got = set(BATCH[lang])
        assert expected == got, f"{lang}: diff={expected ^ got}"
        for k in got:
            assert k in zh, f"{lang}: {k} not in template"
            src_ph = set()
            meta = zh.get("@" + k)
            if meta and "placeholders" in meta:
                src_ph = set(meta["placeholders"])
            dst_ph = set(re.findall(r"{(\w+)}", BATCH[lang][k]))
            assert src_ph == dst_ph, f"{lang}:{k} placeholder mismatch {src_ph} vs {dst_ph}"
    for lang, filename in LOCALE_FILE.items():
        path = ARB_DIR / filename
        added = append_keys(path, BATCH[lang])
        print(f"{filename}: appended {len(added)} keys")


if __name__ == "__main__":
    main()
